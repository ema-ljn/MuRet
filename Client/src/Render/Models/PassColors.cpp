glm::vec3 Lookup(std::span<const Entry> entries, std::uint16_t model, glm::vec3 fallback)
{
    const auto found = std::lower_bound(entries.begin(), entries.end(), model,
                                        [](const Entry& entry, std::uint16_t value) { return entry.model < value; });
    return found != entries.end() && found->model == model ? found->color : fallback;
}

Color Opaque(glm::vec3 color)
{
    return Color{color.x, color.y, color.z, 1.0f};
}
