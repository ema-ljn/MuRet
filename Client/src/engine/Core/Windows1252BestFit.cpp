std::uint8_t Windows1252XpCodeUnit(char16_t codeUnit)
{
    if (codeUnit <= 0x7f || (codeUnit >= 0xa0 && codeUnit <= 0xff))
    {
        return static_cast<std::uint8_t>(codeUnit);
    }

    for (unsigned int offset = 0; offset < 32; ++offset)
    {
        const auto byte = static_cast<std::uint8_t>(0x80U + offset);
        if (Windows1252CodePoint(byte) == static_cast<char32_t>(codeUnit))
        {
            return byte;
        }
    }

    const auto mapping =
        std::lower_bound(BestFits.begin(), BestFits.end(), codeUnit,
                         [](const BestFit& candidate, char16_t value) { return candidate.codeUnit < value; });
    if (mapping != BestFits.end() && mapping->codeUnit == codeUnit)
    {
        return mapping->byte;
    }
    return static_cast<std::uint8_t>('?');
}

std::optional<std::string> EncodeWindows1252Xp(std::string_view utf8)
{
    std::string encoded;
    std::size_t offset = 0;
    while (offset < utf8.size())
    {
        const auto codePoint = ReadUtf8CodePoint(utf8, offset);
        if (!codePoint.has_value())
        {
            return std::nullopt;
        }
        if (*codePoint <= 0xffff)
        {
            encoded.push_back(static_cast<char>(Windows1252XpCodeUnit(static_cast<char16_t>(*codePoint))));
            continue;
        }
        const char32_t supplementary = *codePoint - 0x10000;
        const char16_t highSurrogate = static_cast<char16_t>(0xd800 + (supplementary >> 10));
        const char16_t lowSurrogate = static_cast<char16_t>(0xdc00 + (supplementary & 0x3ff));
        encoded.push_back(static_cast<char>(Windows1252XpCodeUnit(highSurrogate)));
        encoded.push_back(static_cast<char>(Windows1252XpCodeUnit(lowSurrogate)));
    }
    return encoded;
}
