[[nodiscard]] char FoldPathCharacter(char character)
{
    auto folded = static_cast<unsigned char>(character);
    if (folded == '\\')
        return '/';
    if (folded >= 'A' && folded <= 'Z')
        folded = static_cast<unsigned char>(folded + ('a' - 'A'));
    return static_cast<char>(folded);
}

[[nodiscard]] bool PathsMatch(std::string_view left, std::string_view right)
{
    if (left.size() != right.size())
        return false;

    for (std::size_t index = 0; index < left.size(); ++index)
    {
        if (FoldPathCharacter(left[index]) != FoldPathCharacter(right[index]))
            return false;
    }
    return true;
}

