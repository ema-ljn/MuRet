TEST(OriginalRetainedMathTest, NativeLeafConversionsStaySeparateFromEvaluation)
{
    static_assert(WaveCases.size() == 1020);
    EXPECT_EQ(std::fegetround(), FE_TONEAREST);
    for (std::size_t index = 0; index < WaveCases.size(); ++index)
    {
        SCOPED_TRACE(index);
        const auto& row = WaveCases[index];
        const float time = std::bit_cast<float>(row.timeBits);
        const auto first = Math::FirstLeafSine(time);
        const auto second = Math::SecondLeafSine(time);
        EXPECT_EQ(first.argumentRetained, row.firstRetained);
        EXPECT_EQ(second.argumentRetained, row.secondRetained);
        EXPECT_EQ(first.value.classification, row.classification);
        EXPECT_EQ(second.value.classification, row.classification);
        const auto h1 = Math::TruncateLeafSine(first.value);
        const auto h2 = Math::TruncateLeafSine(second.value);
        EXPECT_EQ(h1.integer, row.first);
        EXPECT_EQ(h2.integer, row.second);
        EXPECT_EQ(h1.valid, row.firstValid);
        EXPECT_EQ(h2.valid, row.secondValid);
        EXPECT_EQ(static_cast<std::uint32_t>(h1.integer), static_cast<std::uint32_t>(row.first));
        EXPECT_EQ(static_cast<std::uint32_t>(h2.integer), static_cast<std::uint32_t>(row.second));
    }
}
TEST(OriginalRetainedMathTest, DistinguishesValidMinimumFromMaskedInvalid)
{
    constexpr Math::Retained64 minimum{std::uint64_t{1} << 63U, 0, Math::RetainedClass::Finite, true};
    constexpr Math::Retained64 positiveLimit{std::uint64_t{1} << 63U, 0, Math::RetainedClass::Finite, false};
    const auto valid = Math::TruncateLeafSine(minimum);
    const auto invalid = Math::TruncateLeafSine(positiveLimit);
    EXPECT_TRUE(valid.valid);
    EXPECT_FALSE(invalid.valid);
    EXPECT_EQ(valid.integer, std::numeric_limits<std::int64_t>::min());
    EXPECT_EQ(invalid.integer, valid.integer);
    for (const auto classification : {Math::RetainedClass::Infinity, Math::RetainedClass::NaN})
    {
        const auto result = Math::TruncateLeafSine({0, 0, classification, false});
        EXPECT_FALSE(result.valid);
        EXPECT_EQ(result.integer, valid.integer);
    }
}
