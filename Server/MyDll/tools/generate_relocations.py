"""Emit the pinned GS boot operand table from the two text research inputs."""

from __future__ import annotations

import argparse
import hashlib
import re
import struct
from pathlib import Path

ASM_SHA256 = "82912f0c436f82b521aae9cda8581e5bf19f1b61437f960db587906aea83c3d4"
TABLE_SHA256 = "54bfc0fc6ef95a0359b3e23734e27fbb7fabdcf6734f1bcc3e0f3595988dfc10"
OPERANDS_SHA256 = "51997304d4e2ab8f942d9dba2306e737114b1c08b1494abf4241c07bd8e22d8a"
BANKS = (
    ("ItemAttr", 36, 0, 0x0376A100),
    ("BloodCastle", 159, 0x0376A100, 0x1300),
    ("Obj", 2550, 0x0376B400, 0x011D6680),
    ("MSetBase", 69, 0x04941A80, 0x1400C),
)


def read_pinned(path: Path, sha256: str) -> str:
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != sha256:
        raise ValueError(f"Unexpected SHA-256 for {path}")
    return data.decode("utf-8", errors="replace")


def read_assembly(assembly: str) -> dict[int, int]:
    memory: dict[int, int] = {}
    for match in re.finditer(r"^\s*([0-9a-f]+):\t([0-9a-f]{2}(?: [0-9a-f]{2})*)", assembly, re.M):
        address = int(match[1], 16)
        for offset, byte in enumerate(bytes.fromhex(match[2])):
            memory[address + offset] = byte
    return memory


def collect_rows(table: str, memory: dict[int, int]) -> list[tuple[int, int, int]]:
    rows = []
    for bank, count, base, size in BANKS:
        block = re.search(rf"g_Reloc{bank}\[{count}\]\s*=\s*\{{(.*?)\n\}};", table, re.S)
        if not block:
            raise ValueError(f"Missing bank: {bank}")
        records = re.findall(r"\{(0x[\da-fA-F]+),(\d+),(-?\d+)\}", block[1])
        if len(records) != count:
            raise ValueError(f"Unexpected row count: {bank}")
        for instruction, operand, signed_delta in records:
            site = int(instruction, 16) + int(operand)
            offset = 0x14000 if bank == "MSetBase" and signed_delta == "-1" else int(signed_delta)
            if not 0 <= offset < size or any(site + index not in memory for index in range(4)):
                raise ValueError(f"Invalid {bank} row at 0x{site:08x}")
            old = int.from_bytes(bytes(memory[site + index] for index in range(4)), "little")
            rows.append((site, old, base + offset))
    rows.sort()
    if any(next_row[0] - row[0] < 4 for row, next_row in zip(rows, rows[1:])):
        raise ValueError("Overlapping operand sites")
    if hashlib.sha256(b"".join(struct.pack("<III", *row) for row in rows)).hexdigest() != OPERANDS_SHA256:
        raise ValueError("Unexpected canonical operand digest")
    return rows


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("assembly", type=Path)
    parser.add_argument("bank_table", type=Path)
    args = parser.parse_args()
    try:
        memory = read_assembly(read_pinned(args.assembly, ASM_SHA256))
        rows = collect_rows(read_pinned(args.bank_table, TABLE_SHA256), memory)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    print("// Generated by tools/generate_relocations.py; see docs/research/01-gameserver-boot.md.")
    for site, old, offset in rows:
        print(f"    {{0x{site:08x}UL, 0x{old:08x}UL, 0x{offset:08x}UL}},")


if __name__ == "__main__":
    main()
