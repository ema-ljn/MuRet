// Renames the openlibm symbols this probe builds, so they can sit next to the system libm.
#define FDX2(a, b) a##b
#define FDX1(a, b) FDX2(a, b)
#define FDX(name) FDX1(PROBE_PREFIX, name)
#define sin FDX(sin)
#define cos FDX(cos)
#define tan FDX(tan)
#define acos FDX(acos)
#define log10 FDX(log10)
#define sinf FDX(sinf)
#define cosf FDX(cosf)
#define tanf FDX(tanf)
#define acosf FDX(acosf)
#define __kernel_sin FDX(kernel_sin)
#define __kernel_cos FDX(kernel_cos)
#define __kernel_tan FDX(kernel_tan)
#define __kernel_rem_pio2 FDX(kernel_rem_pio2)
#define __ieee754_rem_pio2 FDX(ieee754_rem_pio2)
#define __ieee754_rem_pio2f FDX(ieee754_rem_pio2f)
#define __kernel_sindf FDX(kernel_sindf)
